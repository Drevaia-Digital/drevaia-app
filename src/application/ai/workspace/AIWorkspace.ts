/**
 * DREVAIA AI Workspace
 *
 * Core domain model shared by every AI workspace.
 * This model is framework-agnostic and independent
 * from React, providers and UI components.
 */

export interface AIWorkspaceSEO {
  title: string;
  description: string;
  keywords: string[];
  slug: string;
}

export interface AIWorkspaceReview {
  score: number;
  strengths: string[];
  improvements: string[];
}

export interface AIWorkspaceRuntime {
  model: string;
  version: string;
}

/**
 * Runtime execution metrics.
 */
export interface AIWorkspaceMetrics {
  durationMs: number;

  provider: string;

  model: string;

  promptTokens?: number;

  completionTokens?: number;

  totalTokens?: number;

  estimatedCost?: number;

  workflow: string;

  stages: string[];

  success: boolean;
}

/**
 * Runtime execution phase.
 */
export interface AIWorkspaceExecutionPhase {
  id: string;

  status:
    | "completed"
    | "skipped"
    | "failed";
}

/**
 * Runtime execution report.
 */
export interface AIWorkspaceExecution {
  phases: AIWorkspaceExecutionPhase[];
}

/**
 * Structured knowledge generated by the Runtime.
 */
export interface AIWorkspaceKnowledge {
  projectId: string;

  workflow: string;

  language: string;

  topic: string;

  subtopic?: string;

  emotion: string;

  emotions: string[];

  intent: string;

  narrative: string;

  collection?: string;

  keywords: string[];

  summary: string;

  score: number;

  editorial: string;
}

export interface AIWorkspaceState {
  /**
   * Current reflection written by the user.
   */
  reflection: string;

  /**
   * Loading state while the Runtime is generating.
   */
  loading: boolean;

  /**
   * Optional error message.
   */
  error: string | null;

  /**
   * Current workflow.
   */
  workflow: string;

  /**
   * Editorial result.
   */
  editorial: string;

  /**
   * Structured knowledge generated
   * during this execution.
   */
  knowledge: AIWorkspaceKnowledge | null;

  /**
   * SEO result.
   */
  seo: AIWorkspaceSEO | null;

  /**
   * Editorial review.
   */
  review: AIWorkspaceReview | null;

  /**
   * Runtime metadata.
   */
  runtime: AIWorkspaceRuntime | null;

  /**
   * Runtime execution metrics.
   */
  metrics: AIWorkspaceMetrics | null;

  /**
   * Runtime execution report.
   */
  execution: AIWorkspaceExecution | null;
}

/**
 * Default Workspace state.
 */
export const INITIAL_AI_WORKSPACE: AIWorkspaceState = {
  reflection: "",

  loading: false,

  error: null,

  workflow: "",

  editorial: "",

  knowledge: null,

  seo: null,

  review: null,

  runtime: null,

  metrics: null,

  execution: null,
};